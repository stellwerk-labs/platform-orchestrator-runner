package rollout

// PostgreSQL storage starts encrypted. SQLite legacy migration and page
// compaction are intentionally absent from this independent fresh-site format.
const postgresStorageVersion = 7
const postgresSchema = `
CREATE TABLE rollout_site (
 id INTEGER PRIMARY KEY CHECK(id=1), org TEXT NOT NULL, runner TEXT NOT NULL, runner_uuid UUID NOT NULL, public_key TEXT NOT NULL
);
CREATE TABLE rollout_workers (worker TEXT PRIMARY KEY,generation BIGINT NOT NULL CHECK(generation>0));
CREATE TABLE rollout_commands (
 id TEXT PRIMARY KEY, digest TEXT NOT NULL, payload BYTEA NOT NULL, progress BYTEA NOT NULL,
 version TEXT NOT NULL, environment TEXT NOT NULL, strategy TEXT NOT NULL,
 owner_worker TEXT NOT NULL DEFAULT '', owner_generation BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE rollout_environments (
 environment TEXT PRIMARY KEY, rollout TEXT NOT NULL UNIQUE REFERENCES rollout_commands(id)
);
CREATE TABLE rollout_artifacts (
 rollout TEXT PRIMARY KEY REFERENCES rollout_commands(id), plan BYTEA NOT NULL,
 review BYTEA NOT NULL, outputs BYTEA, digest TEXT NOT NULL
);
CREATE TABLE rollout_cost_artifacts (
 rollout TEXT PRIMARY KEY REFERENCES rollout_commands(id), content BYTEA NOT NULL, digest TEXT NOT NULL
);
CREATE TABLE rollout_approval_audit (
 rollout TEXT PRIMARY KEY REFERENCES rollout_commands(id), decision TEXT NOT NULL
);
CREATE TABLE rollout_plan_logs (
 rollout TEXT PRIMARY KEY REFERENCES rollout_commands(id), subject TEXT NOT NULL,
 content BYTEA, too_large BOOLEAN NOT NULL
);
CREATE TABLE rollout_pipeline_results (
 rollout TEXT PRIMARY KEY REFERENCES rollout_commands(id), body BYTEA NOT NULL, outputs BYTEA NOT NULL
);
CREATE TABLE rollout_execution_logs (
 rollout TEXT PRIMARY KEY REFERENCES rollout_commands(id), content BYTEA NOT NULL, too_large BOOLEAN NOT NULL
);
CREATE TABLE rollout_effects (
 rollout TEXT NOT NULL REFERENCES rollout_commands(id), step TEXT NOT NULL,
 status TEXT NOT NULL, owner_worker TEXT NOT NULL DEFAULT '', owner_generation BIGINT NOT NULL DEFAULT 0, PRIMARY KEY(rollout,step)
);
CREATE TABLE rollout_no_effect_blocks (
 rollout TEXT PRIMARY KEY REFERENCES rollout_commands(id)
);
CREATE TABLE rollout_plan_uses (
 source_plan TEXT PRIMARY KEY REFERENCES rollout_commands(id),
 rollout TEXT NOT NULL UNIQUE REFERENCES rollout_commands(id)
);
CREATE TABLE rollout_decisions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, rollout TEXT NOT NULL REFERENCES rollout_commands(id),
 kind TEXT NOT NULL, subject TEXT NOT NULL, actor TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE TABLE rollout_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, rollout TEXT NOT NULL REFERENCES rollout_commands(id),
 revision BIGINT NOT NULL, payload BYTEA NOT NULL, acknowledged INTEGER NOT NULL DEFAULT 0,
 UNIQUE(rollout,revision)
);
CREATE TABLE rollout_deliveries (
 event_id BIGINT PRIMARY KEY REFERENCES rollout_events(id), content BYTEA NOT NULL,
 result_owner TEXT UNIQUE REFERENCES rollout_commands(id)
);
CREATE TABLE rollout_storage (
 id INTEGER PRIMARY KEY CHECK(id=1), version INTEGER NOT NULL, identity_check BYTEA NOT NULL,
 catalogue TEXT NOT NULL, application TEXT NOT NULL, system_schema TEXT NOT NULL,
 schema_digest TEXT NOT NULL, structure_digest TEXT NOT NULL, workflow_ready INTEGER NOT NULL DEFAULT 0
);`
